#[test]
fn bundled_standard_library_matches_its_sources() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    fn collect(root: &std::path::Path, dir: &std::path::Path, names: &mut Vec<String>) {
        for entry in std::fs::read_dir(dir).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                collect(root, &path, names);
            } else if path.extension().is_some_and(|extension| extension == "ddr") {
                names.push(
                    path.strip_prefix(root)
                        .unwrap()
                        .with_extension("")
                        .to_str()
                        .unwrap()
                        .replace('\\', "/"),
                );
            }
        }
    }
    let library = root.join("stdlib");
    let mut names = Vec::new();
    collect(&library, &library, &mut names);
    names.sort();
    let quote = |source: &str| {
        let mut output = String::from("\"");
        for character in source.chars() {
            match character {
                '\\' => output.push_str("\\\\"),
                '"' => output.push_str("\\\""),
                '\n' => output.push_str("\\n"),
                '\r' => output.push_str("\\r"),
                '\t' => output.push_str("\\t"),
                '\0' => output.push_str("\\0"),
                character => output.push(character),
            }
        }
        output.push('"');
        output
    };
    let mut expected = String::from("// Generated by selfhost/embed.ddr; edit stdlib/*.ddr and regenerate.\n\npub fn source(name: string) -> string {\n");
    for name in &names {
        let source = std::fs::read_to_string(root.join(format!("stdlib/{name}.ddr"))).unwrap();
        expected += &format!(
            "    if name == {} {{ return {} }}\n",
            quote(name),
            quote(&source)
        );
    }
    expected += "    \"\"\n}\n\npub fn contains(name: string) -> bool {\n";
    for name in &names {
        expected += &format!("    if name == {} {{ return true }}\n", quote(name));
    }
    expected += "    false\n}\n";
    let formatter = std::fs::read_to_string(root.join("runtime/float.ddr")).unwrap();
    expected += &format!(
        "\npub fn float_formatter() -> string {{ {} }}\n",
        quote(&formatter)
    );
    let actual = std::fs::read_to_string(root.join("selfhost/bundled.ddr")).unwrap();
    assert!(actual == expected, "bundled standard library is stale; run `dunder run selfhost/embed.ddr` from the repository root");
}

