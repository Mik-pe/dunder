#[test]
fn bundled_standard_library_matches_its_sources() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let names = [
        "array", "bytes", "hash", "macos", "map", "parse", "set", "sha256", "sys", "text",
    ];
    let mut actual_names: Vec<_> = std::fs::read_dir(root.join("stdlib"))
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .filter(|path| path.extension().is_some_and(|extension| extension == "ddr"))
        .map(|path| path.file_stem().unwrap().to_str().unwrap().to_owned())
        .collect();
    actual_names.sort();
    assert_eq!(
        actual_names, names,
        "update the embedded library generator when adding a standard module"
    );
    let quote = |source: &str| {
        let mut output = String::from("\"");
        for character in source.chars() {
            match character {
                '\\' => output.push_str("\\\\"),
                '"' => output.push_str("\\\""),
                '\n' => output.push_str("\\n"),
                '\r' => output.push_str("\\r"),
                '\t' => output.push_str("\\t"),
                '\0' => output.push_str("\\0"),
                character => output.push(character),
            }
        }
        output.push('"');
        output
    };
    let mut expected = String::from("// Generated by selfhost/embed.ddr; edit stdlib/*.ddr and regenerate.\n\npub fn source(name: string) -> string {\n");
    for name in names {
        let source = std::fs::read_to_string(root.join(format!("stdlib/{name}.ddr"))).unwrap();
        expected += &format!(
            "    if name == {} {{ return {} }}\n",
            quote(name),
            quote(&source)
        );
    }
    expected += "    \"\"\n}\n\npub fn contains(name: string) -> bool {\n";
    for name in names {
        expected += &format!("    if name == {} {{ return true }}\n", quote(name));
    }
    expected += "    false\n}\n";
    let actual = std::fs::read_to_string(root.join("selfhost/bundled.ddr")).unwrap();
    assert!(actual == expected, "bundled standard library is stale; run `dunder run selfhost/embed.ddr` from the repository root");
}

