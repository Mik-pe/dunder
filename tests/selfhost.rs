    // Native ARM64 needs no runner. On x86-64, QEMU is solely a test dependency:
    // the compiler and generated binaries run with an empty tool search path.
    enum Runner {
        Native,
        Qemu(PathBuf),
    }
    impl Runner {
        fn available() -> Option<Self> {
            if cfg!(target_arch = "aarch64") {
                return Some(Self::Native);
            }
            if let Some(path) = std::env::var_os("DUNDER_QEMU_AARCH64") {
                let path = PathBuf::from(path);
                assert!(
                    path.is_file(),
                    "DUNDER_QEMU_AARCH64 must name a QEMU executable"
                );
                return Some(Self::Qemu(fs::canonicalize(path).unwrap()));
            }
            let mut candidates: Vec<_> = std::env::var_os("PATH")
                .map(|paths| {
                    std::env::split_paths(&paths)
                        .map(|p| p.join("qemu-aarch64"))
                        .collect()
                })
                .unwrap_or_default();
            candidates.extend([
                PathBuf::from("/usr/bin/qemu-aarch64-static"),
                PathBuf::from("/workspace/.tools/qemu/usr/bin/qemu-aarch64"),
            ]);
            candidates
                .into_iter()
                .find(|p| p.is_file())
                .map(|p| Self::Qemu(fs::canonicalize(p).unwrap()))
        }

        fn command(&self, image: &Path) -> Command {
            match self {
                Self::Native => Command::new(image),
                Self::Qemu(qemu) => {
                    let mut command = Command::new(qemu);
                    command.arg(image);
                    command
                }
            }
        }

        fn run(&self, image: &Path, cwd: &Path) -> Output {
            self.command(image)
                .current_dir(cwd)
                .env_clear()
                .env("PATH", "/no-external-tools")
                .output()
                .unwrap()
        }
    }

    fn assert_arm64_elf(image: &[u8]) {
        assert!(image.len() >= 64, "truncated ELF header");
        assert_eq!(&image[..7], b"\x7fELF\x02\x01\x01");
        let u16_at = |offset| u16::from_le_bytes(image[offset..offset + 2].try_into().unwrap());
        let u32_at = |offset| u32::from_le_bytes(image[offset..offset + 4].try_into().unwrap());
        let u64_at = |offset| u64::from_le_bytes(image[offset..offset + 8].try_into().unwrap());
        assert_eq!(u16_at(16), 2, "must be an executable");
        assert_eq!(u16_at(18), 183, "must target ARM64 Linux");
        let entry = u64_at(24);
        let table = u64_at(32) as usize;
        let stride = u16_at(54) as usize;
        let count = u16_at(56) as usize;
        assert!(stride >= 56 && count > 0);
        assert!(table
            .checked_add(count * stride)
            .is_some_and(|end| end <= image.len()));
        let mut executable_entry = false;
        for i in 0..count {
            let offset = table + i * stride;
            let kind = u32_at(offset);
            assert_ne!(kind, 2, "selfhost output must not require dynamic linking");
            assert_ne!(kind, 3, "selfhost output must not require an interpreter");
            if kind == 1 {
                let flags = u32_at(offset + 4);
                let file_offset = u64_at(offset + 8);
                let address = u64_at(offset + 16);
                let file_size = u64_at(offset + 32);
                let memory_size = u64_at(offset + 40);
                assert!(file_offset
                    .checked_add(file_size)
                    .is_some_and(|end| end <= image.len() as u64));
                assert!(file_size <= memory_size);
                if flags & 1 != 0 && entry >= address && entry - address < file_size {
                    executable_entry = true;
                }
            }
        }
        assert!(
            executable_entry,
            "entry must lie inside executable file bytes"
        );
    }

