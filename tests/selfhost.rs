    #[test]
    fn dunder_loader_resolves_modules_preserves_diagnostics_and_protects_sources() {
        let work = Work::new();
        let compiler = work.bootstrap();
        let input = work.0.join("main.ddr");
        let output = work.0.join("program");
        let data = work.0.join("pkg/data.ddr");
        fs::create_dir(work.0.join("pkg")).unwrap();
        let data_source = "fn secret()->i32{40}\npub fn answer()->i32{secret()}\n";
        fs::write(&data, data_source).unwrap();
        fs::write(
            work.0.join("pkg/cyclea.ddr"),
            "import .cycleb as b\npub fn seed()->i32{20}\npub fn value()->i32{b.value()*2}\n",
        )
        .unwrap();
        fs::write(
            work.0.join("pkg/cycleb.ddr"),
            "import .cyclea as a\npub fn value()->i32{a.seed()+1}\n",
        )
        .unwrap();
        let main_source = "import pkg.data as numbers\nimport std.parse as decimal\nimport pkg.cyclea as a\nimport pkg.cycleb as b\nfn main(){print(numbers.answer()+i32(decimal.integer(\"2\").value));print(a.value());print(b.value())}\n";
        fs::write(&input, main_source).unwrap();
        work.build(Command::new(&compiler), &input, &output);
        if let Some(runner) = Runner::available() {
            let result = runner.run(&output, &work.0);
            success(
                "dotted imports, aliases, bundled stdlib and cyclic module deduplication",
                &result,
            );
            assert_eq!(result.stdout, b"42\n42\n21\n");
        }
        let previous = fs::read(&output).unwrap();

        fs::write(&input, "import pkg.data\nfn main(){print(data.secret())}\n").unwrap();
        let result = work.invoke_build(Command::new(&compiler), &input, &output);
        assert_eq!(result.status.code(), Some(1));
        let diagnostics = String::from_utf8_lossy(&result.stderr);
        assert!(diagnostics.contains("private"), "{diagnostics}");
        assert!(
            diagnostics.contains(&format!("{}:2:", input.display())),
            "{diagnostics}"
        );
        assert_eq!(fs::read(&output).unwrap(), previous);

        fs::write(&input, "import pkg.data\nfn main(){print(data.answer())}\n").unwrap();
        fs::write(&data, "pub fn answer()->i32 {\n    missing()\n}\n").unwrap();
        let result = work.invoke_build(Command::new(&compiler), &input, &output);
        assert_eq!(result.status.code(), Some(1));
        let diagnostics = String::from_utf8_lossy(&result.stderr);
        assert!(diagnostics.contains("E1000"), "{diagnostics}");
        assert!(
            diagnostics.contains(&format!("{}:2:", data.display())),
            "{diagnostics}"
        );
        assert_eq!(fs::read(&output).unwrap(), previous);

        fs::write(&input, main_source).unwrap();
        fs::write(&data, data_source).unwrap();
        let hard_link = work.0.join("import-hardlink.ddr");
        let symbolic_link = work.0.join("import-symlink.ddr");
        fs::hard_link(&data, &hard_link).unwrap();
        std::os::unix::fs::symlink(&data, &symbolic_link).unwrap();
        for target in [&data, &hard_link, &symbolic_link] {
            let result = work.invoke_build(Command::new(&compiler), &input, target);
            assert_eq!(result.status.code(), Some(1));
            let diagnostics = String::from_utf8_lossy(&result.stderr);
            assert!(
                diagnostics.contains("output must not overwrite source"),
                "{diagnostics}"
            );
            assert_eq!(fs::read_to_string(&data).unwrap(), data_source);
            assert_eq!(fs::read_to_string(&input).unwrap(), main_source);
        }
    }

    #[test]
    fn dunder_compiler_rebuilds_itself_and_checks_fixed_point_when_arm64_can_run() {
        let work = Work::new();
        let stage1 = work.bootstrap();
        let stage2 = work.0.join("stage2");
        work.build(Command::new(&stage1), &compiler_source(), &stage2);
        let Some(runner) = Runner::available() else {
            eprintln!("Dunder compiled itself to an ARM64 ELF; stage3 execution requires DUNDER_QEMU_AARCH64 or qemu-aarch64 on PATH");
            return;
        };
        let stage3 = work.0.join("stage3");
        work.build(runner.command(&stage2), &compiler_source(), &stage3);
        assert_eq!(
            fs::read(&stage2).unwrap(),
            fs::read(&stage3).unwrap(),
            "stage2 and stage3 compiler bytes must match"
        );
        check_programs(&work, &stage3, Some(&runner), Some(&runner));
        let root = Path::new(env!("CARGO_MANIFEST_DIR"));
        for entry in [
            "arena/main",
            "collections",
            "enums",
            "filesystem",
            "iterators",
            "numeric/main",
            "recursion",
            "sorting",
            "standard",
            "structs",
            "tokenizer",
            "utf8",
        ] {
            let source = root.join("dogfood").join(entry).with_extension("ddr");
            let reference = work.0.join("dogfood-bootstrap");
            let built = work.invoke_build(
                Command::new(env!("CARGO_BIN_EXE_dunder")),
                &source,
                &reference,
            );
            success(entry, &built);
            let expected = Runner::Native.run(&reference, &work.0);
            success(entry, &expected);
            let program = work.0.join("dogfood-stage3");
            work.build(runner.command(&stage3), &source, &program);
            let actual = runner.run(&program, &work.0);
            success(entry, &actual);
            assert_eq!(actual.stdout, expected.stdout, "{entry}");
            assert_eq!(actual.stderr, expected.stderr, "{entry}");
        }
        let higher_order = work.0.join("chained-functions");
        work.build(
            runner.command(&stage3),
            &root.join("examples/functions.ddr"),
            &higher_order,
        );
        let actual = runner.run(&higher_order, &work.0);
        success("stage3 chained function values", &actual);
        assert_eq!(actual.stdout, b"42\n42\n-42\n");

        let app = work.0.join("check.ddr");
        let module = work.0.join("unused.ddr");
        fs::write(&app, "import unused\nfn main(){counter:=42;print(counter)}").unwrap();
        fs::write(&module, "pub fn dead(){value:=missing()}").unwrap();
        let check = || {
            runner
                .command(&stage3)
                .args(["check", "--agent"])
                .arg(&app)
                .current_dir(&work.0)
                .env_clear()
                .env("PATH", "/no-external-tools")
                .output()
                .unwrap()
        };
        let invalid = check();
        assert_eq!(invalid.status.code(), Some(1));
        let diagnostic = String::from_utf8(invalid.stdout).unwrap();
        assert!(
            diagnostic.contains("\"kind\":\"error\"")
                && diagnostic.contains("unused.ddr\",\"start\":21,\"end\":28"),
            "{diagnostic}"
        );
        fs::write(&module, "pub fn dead(){value:=2}").unwrap();
        let valid = check();
        success("selfhost check --agent", &valid);
        let records = String::from_utf8(valid.stdout).unwrap();
        assert!(
            records.contains("\"name\":\"value\",\"type\":\"i32\"")
                && records.contains("\"name\":\"counter\",\"type\":\"i32\"")
                && records.contains("\"kind\":\"ok\",\"modules\":2"),
            "{records}"
        );
        let project = Path::new(env!("CARGO_MANIFEST_DIR")).join("projects/tabell");
        let tabell = work.0.join("tabell");
        work.build(runner.command(&stage3), &project.join("main.ddr"), &tabell);
        let result = runner
            .command(&tabell)
            .arg(project.join("expenses.csv"))
            .args(["team", "cents"])
            .current_dir(&work.0)
            .env_clear()
            .env("PATH", "/no-external-tools")
            .output()
            .unwrap();
        success("stage3-built Tabell", &result);
        assert_eq!(
            result.stdout,
            fs::read(project.join("expected.csv")).unwrap()
        );
    }
