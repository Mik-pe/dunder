    fn check_programs(
        work: &Work,
        compiler: &Path,
        compiler_runner: Option<&Runner>,
        program_runner: Option<&Runner>,
    ) {
        // Exercise direct signed offsets, immediate-address offsets and the
        // large-offset fallback in the Dunder-written backend, including borrows.
        let boundaries = [0, 31, 32, 510, 511, 519];
        let mut frame_source = String::from("fn bump(v:&mut i32){v=v+10}\nfn main(){\n");
        for slot in 0..520 {
            frame_source += &format!("var v{slot}:={slot}\n");
        }
        for slot in boundaries {
            frame_source += &format!("bump(&mut v{slot})\n");
        }
        for slot in 0..520 {
            let expected = slot + if boundaries.contains(&slot) { 10 } else { 0 };
            frame_source += &format!("assert(v{slot}=={expected})\n");
        }
        frame_source += "print(42)\n}";
        let mut programs = PROGRAMS.to_vec();
        programs.push(("frame_offsets", &frame_source, "42\n"));
        for (name, source, expected) in programs {
            let reference_image = dunder::compile(source).unwrap_or_else(|error| {
                panic!(
                    "invalid {name} test fixture: {}",
                    error.render(name, source)
                )
            });
            let reference = work.0.join(format!("{name}.reference"));
            fs::write(&reference, reference_image).unwrap();
            use std::os::unix::fs::PermissionsExt;
            fs::set_permissions(&reference, fs::Permissions::from_mode(0o755)).unwrap();
            let reference_result = Runner::Native.run(&reference, &work.0);
            success(&format!("Rust reference for {name}"), &reference_result);
            assert_eq!(
                reference_result.stdout,
                expected.as_bytes(),
                "Rust reference for {name}"
            );
            let input = work.0.join(format!("{name}.ddr"));
            let output = work.0.join(format!("{name}.elf"));
            fs::write(&input, source).unwrap();
            let command = compiler_runner
                .map_or_else(|| Command::new(compiler), |runner| runner.command(compiler));
            work.build(command, &input, &output);
            if let Some(runner) = program_runner {
                let result = runner.run(&output, &work.0);
                success(name, &result);
                assert_eq!(result.stdout, reference_result.stdout, "{name}");
                assert_eq!(
                    result.status.code(),
                    reference_result.status.code(),
                    "{name}"
                );
            }
        }
    }

